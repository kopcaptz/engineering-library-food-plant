        fieldIds: ['c1_hf1', 'c1_hf2', 'c1_hfg2'],
        message: lang === 'he'
          ? 'שימו לב: הלחצים והאנתלפיות הוזנו ידנית (מחוץ לנקודות הייחוס המובנות של טבלת הרוויה) — ודאו לפי טבלאות קיטור רווי שהערכים h_f1, h_f2 ו-h_fg2 תואמים ל-P₁ ול-P₂.'
          : raw
